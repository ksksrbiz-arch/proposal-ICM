// Generates context/references/gates.md from the code catalog so docs cannot drift from the gates.
import {writeFile, readFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {CODES} from '../lib/gates/catalog.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
export function render() {
  const byStage = {};
  for (const e of Object.values(CODES)) (byStage[e.stage] ??= []).push(e);
  const order = ['brief', 'research', 'design', 'build', 'qa', 'review', 'publish', 'register', 'any'];
  let out = '# Gate codes\n\nGenerated by `npm run docs:gates` from `lib/gates/catalog.mjs`. Do not edit by hand; `npm run check` fails if it is stale. A gate prints every issue of the first failing stage as `[code] message`; `gate <project> all` shows every stage.\n';
  for (const stage of order) {
    if (!byStage[stage]) continue;
    out += `\n## ${stage === 'any' ? 'Any stage' : stage}\n\n| Code | Meaning | Repair |\n| --- | --- | --- |\n`;
    for (const e of byStage[stage]) out += `| \`${e.code}\` | ${e.meaning} | ${e.fix} |\n`;
  }
  return out;
}
const target = resolve(root, 'context/references/gates.md');
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const current = await readFile(target, 'utf8').catch(() => '');
    if (current !== render()) { console.error('context/references/gates.md is stale: run npm run docs:gates'); process.exitCode = 1; }
  } else await writeFile(target, render());
}
